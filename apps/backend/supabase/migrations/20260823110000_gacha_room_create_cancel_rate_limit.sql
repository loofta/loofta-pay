-- LOO-16: stop a user from repeatedly creating, funding, cancelling, and refunding rooms at
-- Loofta's expense. Three paid creator cancellations in a rolling ten-minute window block all
-- new room creation for that user for one hour.
--
-- A cancellation is counted only when the room creator is the sole paid participant being
-- archived. Empty/unpaid room cleanup has no on-chain cost and deliberately does not count.

CREATE TABLE gacha_room_create_cancel_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id text NOT NULL,
  room_id uuid NOT NULL UNIQUE,
  cancelled_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE INDEX gacha_room_create_cancel_events_user_time_idx
  ON gacha_room_create_cancel_events (user_id, cancelled_at DESC);

CREATE TABLE gacha_room_creation_cooldowns (
  user_id text PRIMARY KEY,
  blocked_until timestamptz NOT NULL,
  triggered_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  updated_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

ALTER TABLE gacha_room_create_cancel_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE gacha_room_creation_cooldowns ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON gacha_room_create_cancel_events, gacha_room_creation_cooldowns FROM anon, authenticated;
GRANT ALL ON gacha_room_create_cancel_events, gacha_room_creation_cooldowns TO service_role;
GRANT USAGE, SELECT ON SEQUENCE gacha_room_create_cancel_events_id_seq TO service_role;

CREATE POLICY "service_gacha_room_create_cancel_events_all"
  ON gacha_room_create_cancel_events FOR ALL
  USING (true) WITH CHECK (true);

CREATE POLICY "service_gacha_room_creation_cooldowns_all"
  ON gacha_room_creation_cooldowns FOR ALL
  USING (true) WITH CHECK (true);

CREATE OR REPLACE FUNCTION record_gacha_paid_creator_cancellation() RETURNS trigger AS $$
DECLARE
  room_creator_id text;
  live_participant_count int;
  recent_cancel_count int;
  event_recorded boolean := false;
BEGIN
  IF NEW.payment_tx_hash IS NULL THEN
    RETURN NEW;
  END IF;

  SELECT created_by_user_id INTO room_creator_id
  FROM gacha_rooms
  WHERE id = NEW.room_id;

  IF room_creator_id IS DISTINCT FROM NEW.user_id THEN
    RETURN NEW;
  END IF;

  -- gacha_leave_waiting_room archives the participant before deleting the live seat. Exactly one
  -- live participant means this paid creator departure is the create/cancel cycle that cancels
  -- the room; a creator leaving a room that still has other players is not counted.
  SELECT count(*) INTO live_participant_count
  FROM gacha_room_participants
  WHERE room_id = NEW.room_id;

  IF live_participant_count <> 1 THEN
    RETURN NEW;
  END IF;

  PERFORM pg_advisory_xact_lock(hashtextextended('gacha-create-cancel-limit:' || NEW.user_id, 0));

  INSERT INTO gacha_room_create_cancel_events (user_id, room_id, cancelled_at)
  VALUES (NEW.user_id, NEW.room_id, clock_timestamp())
  ON CONFLICT (room_id) DO NOTHING
  RETURNING true INTO event_recorded;

  IF NOT COALESCE(event_recorded, false) THEN
    RETURN NEW;
  END IF;

  SELECT count(*) INTO recent_cancel_count
  FROM gacha_room_create_cancel_events
  WHERE user_id = NEW.user_id
    AND cancelled_at >= clock_timestamp() - interval '10 minutes';

  IF recent_cancel_count >= 3 THEN
    INSERT INTO gacha_room_creation_cooldowns (user_id, blocked_until, triggered_at, updated_at)
    VALUES (
      NEW.user_id,
      clock_timestamp() + interval '1 hour',
      clock_timestamp(),
      clock_timestamp()
    )
    ON CONFLICT (user_id) DO UPDATE SET
      blocked_until = GREATEST(
        gacha_room_creation_cooldowns.blocked_until,
        EXCLUDED.blocked_until
      ),
      triggered_at = EXCLUDED.triggered_at,
      updated_at = EXCLUDED.updated_at;
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

DROP TRIGGER IF EXISTS record_gacha_paid_creator_cancellation_trigger ON gacha_room_departures;
CREATE TRIGGER record_gacha_paid_creator_cancellation_trigger
  AFTER INSERT ON gacha_room_departures
  FOR EACH ROW EXECUTE FUNCTION record_gacha_paid_creator_cancellation();

CREATE OR REPLACE FUNCTION enforce_gacha_room_creation_cooldown() RETURNS trigger AS $$
DECLARE
  cooldown_until timestamptz;
BEGIN
  IF NEW.status <> 'waiting' OR NEW.created_by_user_id IS NULL THEN
    RETURN NEW;
  END IF;

  PERFORM pg_advisory_xact_lock(hashtextextended(
    'gacha-create-cancel-limit:' || NEW.created_by_user_id,
    0
  ));

  SELECT blocked_until INTO cooldown_until
  FROM gacha_room_creation_cooldowns
  WHERE user_id = NEW.created_by_user_id
    AND blocked_until > clock_timestamp();

  IF cooldown_until IS NOT NULL THEN
    RAISE EXCEPTION 'GACHA_ROOM_CREATION_COOLDOWN:%',
      floor(extract(epoch FROM cooldown_until) * 1000)::bigint;
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

DROP TRIGGER IF EXISTS enforce_gacha_room_creation_cooldown_trigger ON gacha_rooms;
CREATE TRIGGER enforce_gacha_room_creation_cooldown_trigger
  BEFORE INSERT ON gacha_rooms
  FOR EACH ROW EXECUTE FUNCTION enforce_gacha_room_creation_cooldown();
