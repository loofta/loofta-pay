-- LOO-9: make a settled room's "run it back" action create one shared next room.
--
-- The new room is still a normal waiting room: every player pays a fresh entry, and any
-- unclaimed seat can be filled by the normal public browser (or the private invite). The
-- rematch tables only remember which settled room owns the next room and which real players
-- were invited to it. Keeping this relationship out of a JSON column makes the operation
-- idempotent and gives the API an authoritative membership check.

CREATE TABLE IF NOT EXISTS gacha_rematch_groups (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  source_room_id uuid NOT NULL UNIQUE REFERENCES gacha_rooms(id),
  next_room_id uuid NOT NULL UNIQUE REFERENCES gacha_rooms(id),
  claim_deadline timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS gacha_rematch_members (
  group_id uuid NOT NULL REFERENCES gacha_rematch_groups(id) ON DELETE CASCADE,
  source_participant_id uuid NOT NULL REFERENCES gacha_room_participants(id),
  user_id text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (group_id, user_id),
  UNIQUE (group_id, source_participant_id)
);

CREATE INDEX IF NOT EXISTS gacha_rematch_members_user_idx
  ON gacha_rematch_members (user_id, created_at DESC);

ALTER TABLE gacha_rematch_groups ENABLE ROW LEVEL SECURITY;
ALTER TABLE gacha_rematch_members ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON gacha_rematch_groups FROM anon, authenticated;
REVOKE ALL ON gacha_rematch_members FROM anon, authenticated;

DROP POLICY IF EXISTS service_gacha_rematch_groups_all ON gacha_rematch_groups;
CREATE POLICY service_gacha_rematch_groups_all ON gacha_rematch_groups
  FOR ALL USING (true) WITH CHECK (true);
DROP POLICY IF EXISTS service_gacha_rematch_members_all ON gacha_rematch_members;
CREATE POLICY service_gacha_rematch_members_all ON gacha_rematch_members
  FOR ALL USING (true) WITH CHECK (true);

-- One source room can only ever have one next room. The source-room advisory lock protects the
-- read-then-insert sequence when several players click the button at the same time.
CREATE OR REPLACE FUNCTION gacha_create_rematch_group(
  p_source_room_id uuid,
  p_requesting_user_id text,
  p_invite_code text DEFAULT NULL,
  p_claim_window_seconds int DEFAULT 60
) RETURNS TABLE (
  group_id uuid,
  next_room_id uuid,
  claim_deadline timestamptz,
  invite_code text,
  config_key text,
  name text,
  seats int,
  entry_usdc numeric,
  is_private boolean
) AS $$
DECLARE
  source_room gacha_rooms%ROWTYPE;
  existing_group gacha_rematch_groups%ROWTYPE;
  next_room gacha_rooms%ROWTYPE;
  created_group_id uuid;
  next_room_number bigint;
  normalized_invite_code text;
  normalized_name text;
  deadline timestamptz;
BEGIN
  IF p_claim_window_seconds IS NULL OR p_claim_window_seconds < 0 OR p_claim_window_seconds > 3600 THEN
    RAISE EXCEPTION 'Invalid rematch claim window';
  END IF;

  PERFORM pg_advisory_xact_lock(hashtextextended('gacha-rematch:' || p_source_room_id::text, 0));

  SELECT * INTO source_room
  FROM gacha_rooms
  WHERE id = p_source_room_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Source Gacha room not found';
  END IF;
  IF source_room.status <> 'settled' THEN
    RAISE EXCEPTION 'This room is not settled yet';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM gacha_room_participants
    WHERE room_id = p_source_room_id AND user_id = p_requesting_user_id
  ) THEN
    RAISE EXCEPTION 'Only a room participant can run it back';
  END IF;

  SELECT * INTO existing_group
  FROM gacha_rematch_groups
  WHERE source_room_id = p_source_room_id;

  IF FOUND THEN
    IF NOT EXISTS (
      SELECT 1 FROM gacha_rematch_members AS existing_member
      WHERE existing_member.group_id = existing_group.id
        AND existing_member.user_id = p_requesting_user_id
    ) THEN
      RAISE EXCEPTION 'You were not part of this rematch group';
    END IF;

    SELECT * INTO next_room FROM gacha_rooms WHERE id = existing_group.next_room_id;
    RETURN QUERY SELECT
      existing_group.id,
      next_room.id,
      existing_group.claim_deadline,
      next_room.invite_code,
      next_room.config_key,
      next_room.name,
      next_room.seats,
      next_room.entry_usdc,
      next_room.is_private;
    RETURN;
  END IF;

  -- The bearer code is generated by the API and only matters for a private next room.
  normalized_invite_code := NULLIF(btrim(p_invite_code), '');
  IF source_room.is_private AND normalized_invite_code IS NULL THEN
    RAISE EXCEPTION 'Private rematch rooms require an invite code';
  END IF;
  IF NOT source_room.is_private THEN
    normalized_invite_code := NULL;
  END IF;

  PERFORM pg_advisory_xact_lock(hashtextextended('gacha-room-number:' || source_room.config_key, 0));
  SELECT COALESCE(max(numbered_room.room_number), 0) + 1 INTO next_room_number
  FROM gacha_rooms AS numbered_room
  WHERE numbered_room.config_key = source_room.config_key;

  normalized_name := left(COALESCE(NULLIF(btrim(source_room.name), ''), 'Run it back') || ' · again', 24);
  INSERT INTO gacha_rooms (
    config_key, pack_type, seats, entry_usdc, exclusion_count, status, room_number, name,
    is_private, created_by_user_id, invite_code
  ) VALUES (
    source_room.config_key, source_room.pack_type, source_room.seats, source_room.entry_usdc,
    source_room.exclusion_count, 'waiting', next_room_number, normalized_name,
    source_room.is_private, p_requesting_user_id, normalized_invite_code
  ) RETURNING * INTO next_room;

  deadline := now() + make_interval(secs => p_claim_window_seconds);
  INSERT INTO gacha_rematch_groups (source_room_id, next_room_id, claim_deadline)
  VALUES (p_source_room_id, next_room.id, deadline)
  RETURNING id INTO created_group_id;

  INSERT INTO gacha_rematch_members (group_id, source_participant_id, user_id)
  SELECT created_group_id, participant.id, participant.user_id
  FROM gacha_room_participants AS participant
  WHERE participant.room_id = p_source_room_id
    AND participant.user_id NOT LIKE 'bot-%';

  RETURN QUERY SELECT
    created_group_id,
    next_room.id,
    deadline,
    next_room.invite_code,
    next_room.config_key,
    next_room.name,
    next_room.seats,
    next_room.entry_usdc,
    next_room.is_private;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

REVOKE ALL ON FUNCTION gacha_create_rematch_group(uuid, text, text, int) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION gacha_create_rematch_group(uuid, text, text, int) TO service_role;

-- During the short rematch window, public newcomers cannot consume seats that are still reserved
-- for source-room players. Once the deadline passes, the same waiting room naturally backfills
-- through the public browser. Private rooms skip this guard because their invite code is already
-- the access control boundary.
CREATE OR REPLACE FUNCTION enforce_gacha_room_seat_cap() RETURNS trigger AS $$
DECLARE
  room_seats int;
  current_count int;
  next_seat int;
  rematch_group_id uuid;
  rematch_deadline timestamptz;
  pending_members int;
  is_rematch_member boolean;
  room_is_private boolean;
BEGIN
  SELECT seats, is_private INTO room_seats, room_is_private
  FROM gacha_rooms
  WHERE id = NEW.room_id
  FOR UPDATE;
  IF room_seats IS NULL THEN
    RAISE EXCEPTION 'gacha_rooms % not found', NEW.room_id;
  END IF;

  SELECT id, claim_deadline INTO rematch_group_id, rematch_deadline
  FROM gacha_rematch_groups
  WHERE next_room_id = NEW.room_id;

  IF rematch_group_id IS NOT NULL AND NOT room_is_private AND now() < rematch_deadline THEN
    SELECT EXISTS (
      SELECT 1 FROM gacha_rematch_members
      WHERE group_id = rematch_group_id AND user_id = NEW.user_id
    ) INTO is_rematch_member;

    IF NOT is_rematch_member THEN
      SELECT count(*) INTO pending_members
      FROM gacha_rematch_members AS member
      WHERE member.group_id = rematch_group_id
        AND NOT EXISTS (
          SELECT 1 FROM gacha_room_participants AS participant
          WHERE participant.room_id = NEW.room_id AND participant.user_id = member.user_id
        );
      SELECT count(*) INTO current_count
      FROM gacha_room_participants
      WHERE room_id = NEW.room_id;
      IF current_count + pending_members >= room_seats THEN
        RAISE EXCEPTION 'gacha_rematch_seats_reserved';
      END IF;
    END IF;
  END IF;

  SELECT count(*) INTO current_count FROM gacha_room_participants WHERE room_id = NEW.room_id;
  IF current_count >= room_seats THEN
    RAISE EXCEPTION 'gacha_room % is full (% / % seats)', NEW.room_id, current_count, room_seats;
  END IF;

  SELECT seats.candidate INTO next_seat
  FROM generate_series(1, room_seats) AS seats(candidate)
  WHERE NOT EXISTS (
    SELECT 1 FROM gacha_room_participants
    WHERE room_id = NEW.room_id AND seat_number = seats.candidate
  )
  ORDER BY seats.candidate
  LIMIT 1;

  NEW.seat_number := next_seat;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SET search_path = public;
