/** True when the email's domain (or any parent domain) is a known disposable-mail provider. */
export function isDisposableEmail(email: string | null | undefined): boolean {
  const at = (email ?? '').trim().toLowerCase().lastIndexOf('@');
  if (at < 0) return false;
  const parts = (email as string).trim().toLowerCase().slice(at + 1).split('.');
  for (let i = 0; i < parts.length - 1; i++) {
    if (DISPOSABLE_EMAIL_DOMAINS.has(parts.slice(i).join('.'))) return true;
  }
  return false;
}
